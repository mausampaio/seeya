/**
 * V2-T20 items 1/2's own regression guard for the Linux `.deb` maintainer scripts
 * (`packages/app/build/deb-after-install.sh`/`deb-after-remove.sh`). Same rationale
 * `installer-nsh.test.ts` already gives for the Windows NSIS script: this repo has no `dpkg`/
 * `fpm` wired into `npm test`, and `dist:linux` cannot even build from this project's own
 * Windows dev machine (`dist-platform-check.mjs`'s own guard) — what these tests CAN prove,
 * cheaply and on every OS this suite runs on, is that the content is still there and still shaped
 * the way this task's own report describes having verified it by hand (a throwaway `bash`
 * simulation against a scratch directory, seven cases mirroring the Windows PATH tests — only
 * entry, idempotent reinstall, a foreign file with no marker, a foreign non-regular path).
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const buildDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../../../../packages/app/build',
);
const afterInstall = readFileSync(path.join(buildDir, 'deb-after-install.sh'), 'utf8');
const afterRemove = readFileSync(path.join(buildDir, 'deb-after-remove.sh'), 'utf8');

const MARKER = 'Generated by the seeya .deb postinst';

describe('packages/app/build/deb-after-install.sh', () => {
  it('writes a CLI-dispatching shim to /usr/bin/${executable}, never a symlink to the GUI binary', () => {
    expect(afterInstall).toContain("cat > '/usr/bin/${executable}'");
    // The phrase itself is still allowed in the explanatory comments above (why it's not used) —
    // only an ACTUAL invocation (a line starting with it, not indented as `#` prose) would mean
    // the default template's own symlink registration crept back in.
    expect(afterInstall).not.toMatch(/^\s*update-alternatives\b/m);
    expect(afterInstall).toContain('ELECTRON_RUN_AS_NODE=1');
    expect(afterInstall).toContain(
      "'/opt/${sanitizedProductName}/resources/app.asar/node_modules/@seeya-ai/cli/dist/index.js'",
    );
    expect(afterInstall).toContain(MARKER);
  });

  it('leaves a pre-existing file alone unless it carries the marker (D-025)', () => {
    expect(afterInstall).toContain(`grep -q '${MARKER}'`);
    expect(afterInstall).toContain('leaving it in place');
  });

  it("still runs the default template's own chrome-sandbox/mime/apparmor steps", () => {
    expect(afterInstall).toContain('chrome-sandbox');
    expect(afterInstall).toContain('update-mime-database');
    expect(afterInstall).toContain('update-desktop-database');
    expect(afterInstall).toContain('apparmor_parser');
  });
});

describe('packages/app/build/deb-after-remove.sh', () => {
  it('removes the shim only when the marker confirms this package wrote it', () => {
    expect(afterRemove).toContain(`grep -q '${MARKER}'`);
    expect(afterRemove).toContain("rm -f '/usr/bin/${executable}'");
  });

  it('best-effort removes the systemd --user autostart unit, never failing the removal', () => {
    expect(afterRemove).toContain('seeya-daemon.service');
    expect(afterRemove).toContain('systemctl --user disable');
    expect(afterRemove).toContain('SUDO_USER');
    // Every autostart-cleanup step is allowed to fail silently -- a postrm that exits non-zero
    // can leave dpkg itself in a broken state (this file's own top comment on the risk).
    expect(afterRemove).toMatch(/systemctl --user disable seeya-daemon\.service[^\n]*\|\| true/);
  });

  it("still runs the default template's own apparmor unload/removal steps", () => {
    expect(afterRemove).toContain('apparmor_parser --remove');
  });
});

describe('deb script macros (V2-T20 review fix)', () => {
  // Measured on CI (2026-09-20, the `Build installers` run right after V2-T20 merged): the Linux
  // job died with `Error: Macro name is not defined`, thrown by
  // `app-builder-lib/out/targets/FpmTarget.js#writeConfigFile`. electron-builder substitutes every
  // dollar-brace token in these files and throws on one it does not know -- **including tokens
  // inside shell comments**, which is exactly where the offending `${name}` sat: a comment
  // explaining the substitution mechanism itself. Windows cannot build the Linux target
  // (V2-T12's own `checkPlatformSupport`), so no local gate could have caught it; this test can,
  // on any OS.
  const KNOWN_MACROS = ['executable', 'sanitizedProductName'];

  for (const [name, script] of [
    ['deb-after-install.sh', afterInstall],
    ['deb-after-remove.sh', afterRemove],
  ] as const) {
    it(`${name} uses only macros electron-builder defines`, () => {
      const used = [...script.matchAll(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g)].flatMap(
        (match) => match[1] ?? [],
      );
      const unknown = [...new Set(used)].filter((macro) => !KNOWN_MACROS.includes(macro));

      expect(unknown, `unknown macros in ${name}: ${unknown.join(', ')}`).toEqual([]);
    });
  }
});
