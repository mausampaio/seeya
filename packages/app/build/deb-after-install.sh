# alone; `enable`'s own registration only ever happens from inside the running app), this comment
# just documents that `deb-after-remove.sh`'s own cleanup is a REMOVE/PURGE-time concern, not an
# install-time one, matching dpkg's own maintainer-script conventions (postrm runs the same on
# every removal, postinst is never involved in unregistering anything).
