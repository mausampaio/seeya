#!/bin/bash
# V2-T20 item 1's own Linux measurement: `seeya` on PATH after a `.deb` install.
#
# This REPLACES electron-builder's own default `after-install.tpl` wholesale --
# `deb.afterInstall`/`deb.afterRemove` (`packages/app/electron-builder.yml`) take the whole
# script, never an addition to the default one (measured by reading `FpmTarget.js#createScripts`:
# a custom `afterInstall` path is handed straight to `getResource`, no merge with the template).
# Everything the default template does (apparmor profile, mime/desktop database, chrome-sandbox
# suid bit) is reproduced below UNCHANGED -- see the block comment above each section for what it
# corresponds to in `node_modules/app-builder-lib/templates/linux/after-install.tpl`. The ONE
# deliberate difference is the `/usr/bin/${executable}` section right below.
#
# `${executable}`/`${sanitizedProductName}` are substituted at BUILD time by electron-builder's
# own `writeConfigFile` (`FpmTarget.js`, a regex over dollar-brace tokens) -- both come out "seeya"
# today (`package.json`'s own `productName`/`executableName`), kept as two separate template
# variables for the same reason `windows-installation-scripts.ts`'s own top comment gives: they
# answer two different questions that happen to share a value now.

# ---------------------------------------------------------------------------------------------
# V2-T20 item 1: `/usr/bin/${executable}` becomes a CLI dispatcher, not a symlink to the GUI.
#
# The default template instead runs `update-alternatives --install .../${executable}` pointing at
# `/opt/${sanitizedProductName}/${executable}` directly (the packaged Electron GUI binary) -- so
# typing `seeya` at a prompt would launch the window, not the CLI, and there would be no way to
# run `seeya status` at all (this task's own aceite).
#
# **Measured, not assumed, that repointing this name costs the desktop launcher nothing.** The
# `.desktop` file's own `Exec=` line is generated by `LinuxTargetHelper.js#computeDesktopEntry`
# as the ABSOLUTE path `/opt/${sanitizedProductName}/${executable} %U` -- never
# `/usr/bin/${executable}` -- so clicking the app icon never goes through this symlink/script at
# all. `update-alternatives` is dropped too: it exists to arbitrate between several packages
# providing the SAME command name (e.g. competing "x-www-browser" providers); "seeya" has exactly
# one provider, this package, so the extra indirection buys nothing and only complicates the
# removal side (`deb-after-remove.sh`).
#
# A pre-existing REAL file (not one of our own shims) at this path is left alone -- D-025: this
# package doesn't know what put it there or why, so it doesn't clobber it.
if [[ -e '/usr/bin/${executable}' && ! -f '/usr/bin/${executable}' ]]; then
  echo "warning: /usr/bin/${executable} exists and is not a regular file -- leaving it in place, 'seeya' on PATH may not be this app's CLI" >&2
elif [[ -f '/usr/bin/${executable}' ]] && ! grep -q 'Generated by the seeya .deb postinst' '/usr/bin/${executable}' 2>/dev/null; then
  echo "warning: /usr/bin/${executable} already exists and was not created by this package -- leaving it in place" >&2
else
  cat > '/usr/bin/${executable}' <<'SEEYA_CLI_SHIM'
#!/bin/sh
# Generated by the seeya .deb postinst (V2-T20 item 1) -- dispatches to the CLI bundled inside
# the packaged Electron app, the same ELECTRON_RUN_AS_NODE=1 mechanism the daemon's own launcher
# and the Windows installer's PATH shim already use (adapters/process/daemon-launch.ts,
# packages/app/build/installer.nsh). The marker line above (this comment) is also how
# deb-after-remove.sh recognizes this file as its own before deleting it.
export ELECTRON_RUN_AS_NODE=1
exec '/opt/${sanitizedProductName}/${executable}' '/opt/${sanitizedProductName}/resources/app.asar/node_modules/@seeya-ai/cli/dist/index.js' "$@"
SEEYA_CLI_SHIM
  chmod 0755 '/usr/bin/${executable}'
fi

# ---------------------------------------------------------------------------------------------
# Everything below mirrors app-builder-lib/templates/linux/after-install.tpl verbatim (minus its
# own /usr/bin/${executable} section, replaced above) -- chrome-sandbox suid bit, mime/desktop
# database refresh, AppArmor profile install (Ubuntu 24+).
# ---------------------------------------------------------------------------------------------

# Check if user namespaces are supported by the kernel and working with a quick test:
if ! { [[ -L /proc/self/ns/user ]] && unshare --user true; }; then
    # Use SUID chrome-sandbox only on systems without user namespaces:
    chmod 4755 '/opt/${sanitizedProductName}/chrome-sandbox' || true
else
    chmod 0755 '/opt/${sanitizedProductName}/chrome-sandbox' || true
fi

if hash update-mime-database 2>/dev/null; then
    update-mime-database /usr/share/mime || true
fi

if hash update-desktop-database 2>/dev/null; then
    update-desktop-database /usr/share/applications || true
fi

# Install apparmor profile. (Ubuntu 24+)
# First check if the version of AppArmor running on the device supports our profile.
# This is in order to keep backwards compatibility with Ubuntu 22.04 which does not support abi/4.0.
# In that case, we just skip installing the profile since the app runs fine without it on 22.04.
#
# Those apparmor_parser flags are akin to performing a dry run of loading a profile.
# https://wiki.debian.org/AppArmor/HowToUse#Dumping_profiles
#
# Unfortunately, at the moment AppArmor doesn't have a good story for backwards compatibility.
# https://askubuntu.com/questions/1517272/writing-a-backwards-compatible-apparmor-profile
if apparmor_status --enabled > /dev/null 2>&1; then
  APPARMOR_PROFILE_SOURCE='/opt/${sanitizedProductName}/resources/apparmor-profile'
  APPARMOR_PROFILE_TARGET='/etc/apparmor.d/${executable}'
  if apparmor_parser --skip-kernel-load --debug "$APPARMOR_PROFILE_SOURCE" > /dev/null 2>&1; then
    cp -f "$APPARMOR_PROFILE_SOURCE" "$APPARMOR_PROFILE_TARGET"

    # Updating the current AppArmor profile is not possible and probably not meaningful in a chroot'ed environment.
    # Use cases are for example environments where images for clients are maintained.
    # There, AppArmor might correctly be installed, but live updating makes no sense.
    if ! { [ -x '/usr/bin/ischroot' ] && /usr/bin/ischroot; } && hash apparmor_parser 2>/dev/null; then
      # Extra flags taken from dh_apparmor:
      # > By using '-W -T' we ensure that any abstraction updates are also pulled in.
      # https://wiki.debian.org/AppArmor/Contribute/FirstTimeProfileImport
      apparmor_parser --replace --write-cache --skip-read-cache "$APPARMOR_PROFILE_TARGET"
    fi
  else
    echo "Skipping the installation of the AppArmor profile as this version of AppArmor does not seem to support the bundled profile"
  fi
fi

