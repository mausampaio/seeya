#!/bin/bash
# V2-T20 items 1/2's own Linux `postrm` -- the removal side of `deb-after-install.sh` (read that
# file's own top comment first: `deb.afterInstall`/`deb.afterRemove` REPLACE electron-builder's
# own default `after-remove.tpl` wholesale, so its apparmor/AppArmor-unload logic is reproduced
# below unchanged, not appended to).
#
# `${executable}` is substituted at BUILD time the same way `deb-after-install.sh` documents.

# ---------------------------------------------------------------------------------------------
# V2-T20 item 1: remove the CLI dispatcher `deb-after-install.sh` wrote, IF it is still the one
# this package wrote (D-025: never delete a file this package doesn't recognize as its own --
# same marker-comment check `deb-after-install.sh` used before overwriting it, and the same
# ownership discipline `adapters/autostart/linux.ts`/`macos.ts` already use for THEIR own
# marker-tagged files).
if [[ -f '/usr/bin/${executable}' ]] && grep -q 'Generated by the seeya .deb postinst' '/usr/bin/${executable}' 2>/dev/null; then
  rm -f '/usr/bin/${executable}'
fi

# ---------------------------------------------------------------------------------------------
# V2-T20 item 2: "a desinstalação remove o autostart" (systemd --user unit,
# adapters/autostart/linux.ts) -- best-effort, never fails the package removal (every step below
# is allowed to fail silently, `|| true`/`2>/dev/null`): a `postrm` that exits non-zero can leave
# `dpkg` itself in a broken state, which would be a far worse outcome than an autostart entry
# surviving uninstall.
#
# **Not measured against a real system (same disclaimer `adapters/autostart/linux.ts`'s own top
# comment already carries for the mechanism itself, docs/QUESTOES.md Q-067) -- and this task's
# own "não instale, não desinstale, não execute o instalador" rule means it can't be closed here
# either.** `postrm` runs as root; the unit this task needs to remove lives under the INSTALLING
# user's own home (`~/.config/systemd/user/`, a `systemd --user` unit, never a system-wide one) --
# `$SUDO_USER`/`logname` is the best a root-run maintainer script can do to find that user without
# a second, interactive prompt (dpkg maintainer scripts get none). A `sudo`-less removal (e.g. a
# root shell running `dpkg -r` directly, `$SUDO_USER` unset) leaves the unit behind -- the
# `seeya autostart disable`/`seeya autostart status` CLI commands (V2-T20's own aceite for
# Windows uses the equivalent) still work afterward for someone to run by hand.
seeya_autostart_user="${SUDO_USER:-$(logname 2>/dev/null || true)}"
if [[ -n "$seeya_autostart_user" ]]; then
  seeya_autostart_home=$(getent passwd "$seeya_autostart_user" 2>/dev/null | cut -d: -f6)
  if [[ -n "$seeya_autostart_home" ]]; then
    seeya_autostart_unit="$seeya_autostart_home/.config/systemd/user/seeya-daemon.service"
    if [[ -f "$seeya_autostart_unit" ]]; then
      seeya_autostart_uid=$(id -u "$seeya_autostart_user" 2>/dev/null || true)
      if [[ -n "$seeya_autostart_uid" ]]; then
        sudo -u "$seeya_autostart_user" \
          XDG_RUNTIME_DIR="/run/user/$seeya_autostart_uid" \
          systemctl --user disable seeya-daemon.service >/dev/null 2>&1 || true
      fi
      rm -f "$seeya_autostart_unit" || true
    fi
  fi
fi

APPARMOR_PROFILE_DEST='/etc/apparmor.d/${executable}'

# Remove and unload apparmor profile.
if [ -f "$APPARMOR_PROFILE_DEST" ]; then
  # Unload the profile from the running kernel before deleting the file so the
  # policy is not left enforced until the next reboot. Mirror the chroot guard
  # used in the after-install script -- live AppArmor operations are not
  # meaningful inside a chroot.
  # https://wiki.debian.org/AppArmor/HowToUse
  if apparmor_status --enabled > /dev/null 2>&1; then
    if ! { [ -x '/usr/bin/ischroot' ] && /usr/bin/ischroot; } && hash apparmor_parser 2>/dev/null; then
      apparmor_parser --remove "$APPARMOR_PROFILE_DEST" || true
    fi
  fi
  rm -f "$APPARMOR_PROFILE_DEST"
fi
